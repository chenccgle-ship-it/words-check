import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
if(process.platform!=='win32'||process.arch!=='x64')throw new Error('Build on Windows x64 with Node.js 22+.');
if(process.version!=='v24.19.0')throw new Error('Portable builds currently require Node.js 24.19.0 to match the bundled runtime license.');
const root=fileURLToPath(new URL('../',import.meta.url));
const pkg=JSON.parse(await fs.readFile(path.join(root,'package.json'),'utf8'));
const releaseRoot=path.join(root,'dist',`words-check-${pkg.version}`),output=path.join(releaseRoot,'words check');
const archive=path.join(root,'dist',`words-check-${pkg.version}-windows-x64.zip`);
await fs.mkdir(path.join(output,'runtime'),{recursive:true});
await fs.cp(path.join(root,'app'),path.join(output,'app'),{recursive:true});
await fs.copyFile(process.execPath,path.join(output,'runtime','node.exe'));
await fs.copyFile(path.join(root,'scripts','server.cjs'),path.join(output,'runtime','server.cjs'));
await fs.copyFile(path.join(root,'third-party','Node-LICENSE.txt'),path.join(output,'runtime','Node-LICENSE.txt'));
await fs.copyFile(path.join(root,'scripts','start.vbs'),path.join(output,'启动 words check.vbs'));
await fs.copyFile(path.join(root,'scripts','stop.vbs'),path.join(output,'停止 words check.vbs'));
await fs.copyFile(path.join(root,'data','九年级下册单词表.xlsx'),path.join(output,'九年级下册单词表.xlsx'));
await fs.copyFile(path.join(root,'LICENSE'),path.join(output,'LICENSE.txt'));
await fs.copyFile(path.join(root,'THIRD_PARTY_NOTICES.md'),path.join(output,'第三方说明.md'));
await fs.copyFile(path.join(root,'scripts','使用说明.txt'),path.join(output,'使用说明.txt'));
await fs.writeFile(path.join(output,'runtime','version.txt'),`Node.js ${process.version}\nwords check ${pkg.version}\n`);
const result=spawnSync('powershell.exe',['-NoProfile','-ExecutionPolicy','Bypass','-File',path.join(root,'scripts','create-shortcut.ps1'),'-PackageRoot',output,'-ArchivePath',archive],{stdio:'inherit',windowsHide:true});
if(result.status!==0)throw new Error('Windows packaging failed.');
console.log(archive);
