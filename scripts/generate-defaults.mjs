import fs from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const units=JSON.parse(await fs.readFile(new URL('data/yilin-grade9-lower.json',root),'utf8'));
const samples=units.map(c=>({name:c.name,words:c.words.map(w=>[w.en,w.cn,w.pos||'',w.note||''])}));
await fs.writeFile(new URL('app/default-words.js',root),'// Generated by npm run generate. Edit data/yilin-grade9-lower.json instead.\nconst samples = '+JSON.stringify(samples,null,2)+';\n');
console.log(`Generated ${units.length} courses, ${samples.reduce((sum,c)=>sum+c.words.length,0)} entries.`);
